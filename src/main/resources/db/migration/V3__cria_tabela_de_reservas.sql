-- Reservas. Instantes em TIMESTAMPTZ: o banco guarda o ponto na linha do tempo,
-- nao um horario de parede, o que torna a comparacao entre reservas independente
-- de fuso e de horario de verao.

CREATE TABLE reservas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT         NOT NULL REFERENCES usuarios (id),
    quadra_id    BIGINT         NOT NULL REFERENCES quadras (id),
    inicio       TIMESTAMPTZ    NOT NULL,
    fim          TIMESTAMPTZ    NOT NULL,
    status       VARCHAR(20)    NOT NULL,
    valor        NUMERIC(10, 2) NOT NULL,
    criada_em    TIMESTAMPTZ    NOT NULL,
    cancelada_em TIMESTAMPTZ,
    CONSTRAINT reservas_fim_apos_inicio CHECK (fim > inicio),
    CONSTRAINT reservas_valor_nao_negativo CHECK (valor >= 0),
    CONSTRAINT reservas_status_valido CHECK (status IN ('CONFIRMADA', 'CONCLUIDA', 'CANCELADA')),
    -- Coerencia entre status e data de cancelamento: se cancelada, tem que ter
    -- quando; se nao, nao pode ter. Regra que a aplicacao respeita e o banco garante.
    CONSTRAINT reservas_cancelamento_coerente CHECK (
        (status = 'CANCELADA' AND cancelada_em IS NOT NULL)
        OR (status <> 'CANCELADA' AND cancelada_em IS NULL)
    )
);

CREATE INDEX reservas_por_usuario ON reservas (usuario_id, inicio DESC);
CREATE INDEX reservas_por_quadra_periodo ON reservas (quadra_id, inicio, fim);
