-- Quadras e sua grade semanal de funcionamento.

CREATE TABLE quadras (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120)   NOT NULL,
    modalidade  VARCHAR(30)    NOT NULL,
    preco_hora  NUMERIC(10, 2) NOT NULL,
    ativa       BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT quadras_preco_hora_nao_negativo CHECK (preco_hora >= 0)
);

-- Nome unico sem diferenciar maiusculas: "Quadra 1" e "quadra 1" sao a mesma coisa
-- para quem reserva, entao o banco tambem trata assim.
CREATE UNIQUE INDEX quadras_nome_unico ON quadras (LOWER(nome));

CREATE TABLE horarios_funcionamento (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quadra_id  BIGINT      NOT NULL REFERENCES quadras (id) ON DELETE CASCADE,
    dia_semana VARCHAR(20) NOT NULL,
    abertura   TIME        NOT NULL,
    fechamento TIME        NOT NULL,
    CONSTRAINT horarios_fechamento_apos_abertura CHECK (fechamento > abertura)
);

CREATE INDEX horarios_funcionamento_quadra_dia ON horarios_funcionamento (quadra_id, dia_semana);
